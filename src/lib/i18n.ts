import type { LanguagePreference } from "./api";

export type AppLocale = "zh" | "en";

const LANGUAGE_STORAGE_KEY = "abyss-gazer.language";

export const WEEKDAY_SHORT: Record<AppLocale, readonly string[]> = {
  zh: ["日", "一", "二", "三", "四", "五", "六"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
};

export const WEEKDAY_FULL: Record<AppLocale, readonly string[]> = {
  zh: ["星期日", "星期一", "星期二", "星期三", "星期四", "星期五", "星期六"],
  en: ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"],
};

export function detectSystemLocale(): AppLocale {
  const lang = (navigator.languages?.[0] || navigator.language || "").toLowerCase();
  return lang.startsWith("zh") ? "zh" : "en";
}

export function normalizeLanguagePreference(value: unknown): LanguagePreference {
  if (value === "zh" || value === "en" || value === "system") return value;
  return "system";
}

export function readStoredLanguage(): LanguagePreference {
  try {
    return normalizeLanguagePreference(localStorage.getItem(LANGUAGE_STORAGE_KEY));
  } catch {
    return "system";
  }
}

export function storeLanguage(preference: LanguagePreference) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, preference);
  } catch {
    /* private mode */
  }
}

export function resolveLocale(preference: LanguagePreference): AppLocale {
  if (preference === "zh" || preference === "en") return preference;
  return detectSystemLocale();
}

export function intlTag(locale: AppLocale): string {
  return locale === "zh" ? "zh-CN" : "en";
}

