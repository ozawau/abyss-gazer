import type { LanguagePreference } from "./api";

export type AppLocale = "zh" | "en";

const LANGUAGE_STORAGE_KEY = "abyss-gazer.language";

export const WEEKDAY_SHORT: Record<AppLocale, readonly string[]> = {
  zh: ["日", "一", "二", "三", "四", "五", "六"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
};

